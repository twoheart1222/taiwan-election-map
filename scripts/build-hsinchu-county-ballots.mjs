import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const read = file => JSON.parse(fs.readFileSync(path.join(root, file), 'utf8'));
const source = read('tests/fixtures/hsinchu-county-ballot-draw-2026.json');
const normalize = value => String(value ?? '').normalize('NFKC').replace(/\s+/g, '').replace(/[·‧．・]/g, '.').replace(/啓/g, '啟');
const county = read('data/counties.json').objects.map.geometries.find(g => g.properties.id === '10004').properties;
const towns = read('data/towns/towns-10004.json').objects.map.geometries.map(g => g.properties);
const villages = towns.flatMap(town => read(`data/villages/villages-${town.id}.json`).objects.map.geometries.map(g => ({ ...g.properties, town: town.name })));
const expectedCounts = [3, 68, 31, 248, 366];
// These names are verified visually in the supplied PDF, but are absent from the current roster.
// Keep their draw entries separate; roster additions must use the versioned overrides API.
const allowedMissing = new Set(['10004020009:陳瑞玉', '10004070012:謝玉凌']);
const pendingCandidates = [];
const ballot = { election: '縣長、縣議員、鄉鎮市長、鄉鎮市民代表、村里長',
  source: '新竹縣選舉委員會候選人號次抽籤結果（使用者提供之五份 PDF）',
  date: '2026-10-27', numbers: {}, councilors: {}, townHeads: {}, representatives: {} };
const villageBallots = {};
const scopes = new Map();
let matched = 0;
for (const [kind, document] of Object.entries(source)) {
  if (document.rows.length !== expectedCounts[Number(kind) - 1]) throw new Error(`Unexpected row count: ${kind}`);
  for (const row of document.rows) {
    if (!Number.isInteger(row.no) || row.no < 1 || !row.name || row.page < 1 || row.page > document.pages) throw new Error('Invalid source row');
    const town = towns.find(t => row.area.startsWith('新竹縣' + t.name));
    const district = row.area.match(/第(\d+)選舉區/)?.[1];
    let candidates, numbers, scope;
    if (kind === '1') {
      if (row.area !== '新竹縣') throw new Error(`Unknown county: ${row.area}`);
      candidates = county.candidates; numbers = ballot.numbers; scope = county.id;
    } else if (kind === '2') {
      candidates = county.councilors.find(b => b.district === district)?.candidates;
      numbers = ballot.councilors[district] ||= {}; scope = `${county.id}:councilor:${district}`;
    } else if (kind === '3') {
      candidates = town?.candidates; numbers = ballot.townHeads[town?.id] ||= {}; scope = town?.id;
    } else if (kind === '4') {
      candidates = town?.representatives.find(b => b.district === district)?.candidates;
      numbers = (ballot.representatives[town?.id] ||= {})[district] ||= {}; scope = `${town?.id}:representative:${district}`;
    } else {
      const village = villages.find(v => row.area === '新竹縣' + v.town + v.name);
      candidates = village?.candidates; numbers = villageBallots[village?.id] ||= {}; scope = village?.id;
    }
    if (!scope || !candidates) throw new Error(`Unknown area: ${row.area}`);
    const matches = candidates.filter(c => normalize(c.name) === normalize(row.name));
    if (matches.length !== 1) {
      if (matches.length || !allowedMissing.has(`${scope}:${row.name}`)) throw new Error(`Unresolved name: ${row.area} ${row.name}`);
      pendingCandidates.push({ areaId: scope, area: row.area, name: row.name, ballotNo: row.no, file: document.file, page: row.page,
        existingNames: candidates.map(c => c.name) });
    } else matched++;
    const name = matches[0]?.name || row.name;
    if (Object.hasOwn(numbers, name) || Object.values(numbers).includes(row.no)) throw new Error(`Duplicate draw: ${row.area} ${row.no} ${name}`);
    numbers[name] = row.no;
    scopes.set(scope, { candidates, numbers, area: row.area });
  }
}
for (const [scope, { numbers }] of scopes) {
  const values = Object.values(numbers).sort((a, b) => a - b);
  if (values.some((value, index) => value !== index + 1)) throw new Error(`Non-contiguous numbers: ${scope}`);
}
if (pendingCandidates.length !== 2 || matched !== 714) throw new Error('Re-audit pending candidate differences before rebuilding');
const unlistedExisting = [...scopes].flatMap(([scope, { candidates, numbers, area }]) => candidates
  .filter(candidate => !Object.hasOwn(numbers, candidate.name)).map(candidate => ({ scope, area, name: candidate.name })));
const frozen = value => `Object.freeze(${JSON.stringify(value)})`;
const output = [
  '// 新竹縣選舉委員會 115/10/27 抽籤結果，來源檔案及 SHA-256 見 tests/fixtures/hsinchu-county-ballot-draw-2026.json。',
  '// Generated by scripts/build-hsinchu-county-ballots.mjs; candidate overrides are never modified.',
  `globalThis.FOHsinchuCountyBallotNumbers = ${frozen(ballot)};`,
  'globalThis.FOHsinchuCountyVillageBallots = Object.freeze({',
  ...Object.entries(villageBallots).map(([id, numbers]) => `  ${JSON.stringify(id)}: ${frozen(numbers)},`),
  '});',
  `globalThis.FOHsinchuCountyBallotAudit = ${frozen({ pendingCandidates, unlistedExisting })};`,
];
fs.writeFileSync(path.join(root, 'data/ballot-numbers-hsinchu-county-2026.js'), output.join('\n') + '\n');
console.log(JSON.stringify({ rows: 716, matched, pendingCandidates, unlistedExisting }, null, 2));
